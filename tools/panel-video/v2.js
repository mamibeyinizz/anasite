const { chromium, baglam, birlestir } = require('./lib');
(async () => {
  const b = await chromium.launch();
  const A = await baglam(b, { panel: true, dosya: 'v2-panel' });
  const p = A.p;
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  await p.evaluate(() => { try { localStorage.setItem('qrmsYonKapali:_genel', '1'); } catch (e) {} });
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  A.basla();
  await p.waitForTimeout(200);
  await p.evaluate(() => window.__kart('QR MENU OFFICIAL · PANEL', 'Masalara QR kod nasıl hazırlanır?', 'Teras için dört masayı tek seferde açıp QR kodlarını indirelim.'));
  await p.waitForTimeout(3200);
  await p.evaluate(() => window.__kartKapat());
  await A.alt('Paneli açın; modüller soldaki menüde.', 1);
  await p.waitForTimeout(1200);
  if (await p.isVisible('#qrms-shell-menu-toggle')) await A.dokun('#qrms-shell-menu-toggle', { bekle: 1100 });
  await A.alt('QR Kodlar’ı açın.', 2);
  await p.waitForTimeout(900);
  await A.dokun(await p.waitForSelector('#qrms-shell-sidebar a:has-text("QR Kodlar")'), { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#qmo-onek', { timeout: 60000 });
  await p.waitForTimeout(1200);
  await A.alt('Toplu Oluştur bölümüne masa adını yazın: “Teras”.', 3);
  await p.waitForTimeout(700);
  const onek = await A.dokun('#qmo-onek', { bekle: 300 });
  await onek.type('Teras', { delay: 200 });
  await p.waitForTimeout(900);
  await A.alt('Kaç masa olacağını seçin: 1’den 4’e.', 4);
  await p.waitForTimeout(700);
  const bas = await A.dokun('#qmo-bas', { bekle: 200 });
  await bas.fill('1');
  const bit = await A.dokun('#qmo-bit', { bekle: 200 });
  await bit.fill('');
  await bit.type('4', { delay: 200 });
  await p.waitForTimeout(1300);
  await A.alt('Masaları Oluştur’a basın.', 5);
  await p.waitForTimeout(800);
  await A.dokun('button[name="qmo_masa_toplu_ekle"]', { bekle: 300 });
  await p.waitForLoadState('load');
  await p.waitForSelector('.qmo-chip', { timeout: 60000 });
  await p.waitForTimeout(1000);
  await A.alt('Teras 1–4 oluştu. Teras’a dokunup yalnız o masaları görün.', 6);
  await p.waitForTimeout(800);
  await A.dokun('.qmo-chip[data-grup="teras"]', { bekle: 1200 });
  const satir = await p.$('tr[data-grup="teras"]');
  if (satir) { await satir.scrollIntoViewIfNeeded(); await p.evaluate(() => window.scrollBy(0, -60)); }
  await p.waitForTimeout(700);
  await A.alt('Her masanın kendi QR kodu var. PNG ya da PDF olarak indirip yazdırın.', 7);
  await A.isaretle('tr[data-grup="teras"] img');
  await p.waitForTimeout(2600);
  await A.isaretle('tr[data-grup="teras"] img', false);
  const tum = await p.$('a:has-text("Tümünü Yazdır"), button:has-text("Tümünü Yazdır")');
  if (tum) {
    await A.alt('Tümünü Yazdır ile hepsini tek PDF’te alın; masa başına bir sayfa.', 8);
    await A.dokun(tum, { tikla: false, bekle: 300 });
    await tum.evaluate((e) => e.classList.add('dn-hl'));
    await p.waitForTimeout(2800);
  }
  await A.alt('Masa adı sonradan değişse de basılı QR kod çalışmaya devam eder.', '✓');
  await p.waitForTimeout(3000);
  await A.bitir();
  birlestir([__dirname + '/parca/v2-panel.mp4'], __dirname + '/cikti/2-qr-masa-olusturma.mp4');
  console.log('tamam');
  await b.close();
})().catch((e) => { console.error('HATA', e.message); process.exit(1); });
