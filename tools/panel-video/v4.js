const { chromium, baglam, birlestir } = require('./lib');
(async () => {
  const b = await chromium.launch();
  const A = await baglam(b, { panel: true, dosya: 'v4-panel' });
  const p = A.p;
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  await p.evaluate(() => { try { localStorage.setItem('qrmsYonKapali:_genel', '1'); localStorage.setItem('qrmsYonKapali:qr-analiz', '1'); } catch (e) {} });
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  A.basla();
  await p.waitForTimeout(200);
  await p.evaluate(() => window.__kart('QR MENU OFFICIAL · PANEL', 'Misafir menüde ne arıyor?', 'Menüde aranıp bulunamayan ürünleri görelim; eksik ürünü buradan fark edersiniz.'));
  await p.waitForTimeout(3400);
  await p.evaluate(() => window.__kartKapat());
  await A.alt('Paneli açın; modüller soldaki menüde.', 1);
  await p.waitForTimeout(1200);
  if (await p.isVisible('#qrms-shell-menu-toggle')) await A.dokun('#qrms-shell-menu-toggle', { bekle: 1100 });
  await A.alt('Menü Analizleri’ni açın.', 2);
  await p.waitForTimeout(900);
  await A.dokun(await p.waitForSelector('#qrms-shell-sidebar a:has-text("Menü Analizleri")'), { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#qrms-shell', { timeout: 60000 });
  await p.waitForTimeout(1200);
  await A.alt('Ürünler sekmesine geçin.', 3);
  await p.waitForTimeout(800);
  let sek = null;
  for (const e of await p.$$('#qrms-shell-content a[href*="qrms-an-urunler"]')) { if (await e.isVisible()) { sek = e; break; } }
  await A.dokun(sek, { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#qrms-an-arama-panel', { timeout: 60000 });
  await p.waitForTimeout(1500);
  await A.alt('Aşağıda “Menüde Bulunamayan Aramalar” listesi var.', 4);
  await p.waitForTimeout(600);
  await p.evaluate(() => { const e = document.getElementById('qrms-an-arama-panel'); e.scrollIntoView({ behavior: 'smooth', block: 'start' }); });
  await p.waitForTimeout(1800);
  await p.evaluate(() => window.scrollBy({ top: -70, behavior: 'smooth' }));
  await p.waitForTimeout(900);
  await A.isaretle('#qrms-an-arama-panel');
  await A.alt('Misafirlerin aradığı ama menünüzde olmayan ürünler ve kaç kez arandıkları.', 5);
  await p.waitForTimeout(3600);
  await A.isaretle('#qrms-an-arama-panel', false);
  const cta = await p.$('#qrms-an-arama-cta:not([hidden])');
  if (cta) { await A.isaretle('#qrms-an-arama-cta'); }
  await A.alt('Sık aranan bir ürünü menüye eklemeyi düşünebilirsiniz; ya da ürün varsa adını misafirin yazdığı gibi düzeltin.', 6);
  await p.waitForTimeout(4200);
  await A.alt('Bu liste Plus pakette. Arama verisi ilgiyi gösterir; satış verisi değildir.', '✓');
  await p.waitForTimeout(3200);
  await A.bitir();
  birlestir([__dirname + '/parca/v4-panel.mp4'], __dirname + '/cikti/3-menude-bulunamayan-aramalar.mp4');
  console.log('tamam');
  await b.close();
})().catch((e) => { console.error('HATA', e.message); process.exit(1); });
