const { chromium, baglam, birlestir } = require('./lib');
const BOT = /moment|verif|wait while/i;
(async () => {
  const b = await chromium.launch();
  // --- Panel ---
  const A = await baglam(b, { panel: true, dosya: 'v1-panel' });
  const p = A.p;
  // Kayıt dışı hazırlık: fiyat 320 TL'ye döner.
  await A.git('/wp-admin/post.php?post=77&action=edit', '#rma_price');
  await p.fill('#rma_price', '320');
  await Promise.all([p.waitForNavigation({ timeout: 90000 }), p.click('#publish')]);
  console.log('hazırlık fiyatı', await p.inputValue('#rma_price').catch(() => '?'));
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  await p.evaluate(() => { try { localStorage.setItem('qrmsYonKapali:_genel', '1'); localStorage.setItem('qrmsYonKapali:restoran-menu', '1'); } catch (e) {} });
  await A.git('/wp-admin/admin.php?page=qrms-overview', '#qrms-shell');
  A.basla();
  await p.waitForTimeout(200);
  await p.evaluate(() => window.__kart('QR MENU OFFICIAL · PANEL', 'Fiyat nasıl güncellenir?', 'Bir ürünün fiyatını panelden değiştirip misafirin ekranında görelim.'));
  await p.waitForTimeout(3200);
  await p.evaluate(() => window.__kartKapat());
  await A.alt('Paneli açın; modüller soldaki menüde.', 1);
  await p.waitForTimeout(1500);
  if (await p.isVisible('#qrms-shell-menu-toggle')) await A.dokun('#qrms-shell-menu-toggle', { bekle: 1200 });
  await A.alt('Menü Yönetimi’ne girin.', 2);
  await p.waitForTimeout(900);
  await A.dokun(await p.waitForSelector('#qrms-shell-sidebar a:has-text("Menü Yönetimi")'), { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForTimeout(1500);
  if (BOT.test(await p.title())) console.log('UYARI bot ekranı (hub)');
  await A.alt('Ürünler’i açın.', 3);
  await p.waitForTimeout(900);
  let hedef = null;
  for (const e of await p.$$('#qrms-shell-content a[href*="edit.php?post_type=rma_menu_item"]')) { if (await e.isVisible()) { hedef = e; break; } }
  await A.dokun(hedef, { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#the-list', { timeout: 60000 });
  await p.waitForTimeout(1200);
  await A.alt('Fiyatını değiştireceğiniz ürüne dokunun.', 4);
  await p.waitForTimeout(1000);
  await A.dokun('#post-77 a.row-title', { bekle: 500 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#rma_price', { timeout: 60000 });
  await p.waitForTimeout(1500);
  await A.alt('Fiyat alanına yeni fiyatı yazın: 320 → 340 ₺', 5);
  await p.waitForTimeout(800);
  const f = await A.dokun('#rma_price', { bekle: 300 });
  await f.fill('');
  await p.waitForTimeout(300);
  await f.type('340', { delay: 260 });
  await p.waitForTimeout(1200);
  await A.alt('Güncelle’ye basın.', 6);
  await p.waitForTimeout(900);
  await A.dokun('#publish', { bekle: 300 });
  await p.waitForLoadState('load');
  await p.waitForSelector('#rma_price', { timeout: 60000 });
  await p.waitForTimeout(800);
  console.log('kaydedilen fiyat', await p.inputValue('#rma_price'));
  if (BOT.test(await p.title())) console.log('UYARI bot ekranı (kayıt)');
  await A.alt('Kaydedildi. Menü yeniden basılmadan güncellendi.', '✓');
  await p.waitForTimeout(2600);
  await A.bitir();
  // --- Misafir ---
  await new Promise((r) => setTimeout(r, 4000));
  const B = await baglam(b, { panel: false, dosya: 'v1-menu' });
  const m = B.p;
  await B.git('/?masa=masa-3', '#rma-search');
  const cta = await m.$('.splash-cta');
  if (cta) { await cta.click().catch(() => {}); await m.waitForTimeout(1500); }
  B.basla();
  await B.alt('Misafirin gördüğü menüde “adana kebap” aratalım.', 7);
  await m.waitForTimeout(1600);
  await B.dokun('#rma-search', { bekle: 300 });
  await m.type('#rma-search', 'adana kebap', { delay: 160 });
  await m.waitForTimeout(3200);
  const fiyat = await m.evaluate(() => { const k = [...document.querySelectorAll('.rma-card')].find((x) => /Adana Kebap/.test(x.textContent)); if (!k) return '?'; const f = k.querySelector('.rma-card-price'); f.classList.add('dn-hl'); k.scrollIntoView({ block: 'start' }); window.scrollBy(0, -170); return f.textContent.trim(); });
  console.log('menüdeki fiyat', fiyat);
  await m.waitForTimeout(600);
  await B.alt('Yeni fiyat menüde: 340 ₺. Aynı QR kod, güncel fiyat.', '✓');
  await m.waitForTimeout(3200);
  await B.bitir();
  birlestir([__dirname + '/parca/v1-panel.mp4', __dirname + '/parca/v1-menu.mp4'], __dirname + '/cikti/1-fiyat-guncelleme.mp4');
  console.log('tamam');
  await b.close();
})().catch((e) => { console.error('HATA', e.message); process.exit(1); });
